"""Generate Thai audio for every phrase in app/course.js, in a male and a female neural voice.

Run after changing the course:   pip install edge-tts pythainlp python-crfsuite
                                 python tools/generate_audio.py
Existing files are kept, so only new phrases are generated. Writes:
  audio/male/<id>.mp3, audio/female/<id>.mp3   (id = first 10 hex chars of sha1 of the text)
  app/audio-manifest.js                        (text -> id, and the total bytes the
                                                offline download fetches, for the app)
  app/audio-timing.js                          (when each word is spoken, so the app can
                                                highlight Thai and romanization in time)
"""
import asyncio
import hashlib
import json
import pathlib
import subprocess
import sys

import edge_tts

try:  # Thai syllable counts, so the romanization can follow the voice word by word
    from pythainlp.tokenize import syllable_tokenize
except Exception:  # without it, guess from the word's length
    syllable_tokenize = None

ROOT = pathlib.Path(__file__).resolve().parent.parent
VOICES = {'male': 'th-TH-NiwatNeural', 'female': 'th-TH-PremwadeeNeural'}
RATE = '-15%'  # the app compensates with playbackRate, see THAI_BASE_RATE in app.js


TIMING_FILE = ROOT / 'app' / 'audio-timing.js'
PROGRESS = {'n': 0, 'texts': []}


def key(text):
    return hashlib.sha1(text.encode('utf-8')).hexdigest()[:10]


def syllables(word):
    if syllable_tokenize:
        try:
            return max(1, len([x for x in syllable_tokenize(word) if x.strip()]))
        except Exception:
            pass
    return max(1, round(len(word) / 3))


def word_timing(text, bounds):
    """Flat list, 4 numbers per spoken word: start ms, end ms, where the word ends in
    the text (character index, -1 if not found), and its number of syllables."""
    out, cursor = [], 0
    for b in bounds:
        word = b['text']
        at = text.find(word, cursor)
        end = -1
        if at >= 0:
            end = cursor = at + len(word)
        start = round(b['offset'] / 10000)  # edge-tts times are in 100 ns ticks
        out += [start, start + round(b['duration'] / 10000), end, syllables(word)]
    return out


def save_timing(timing, texts):
    keep = {key(t) for t in texts}
    data = {k: v for k, v in sorted(timing.items()) if k in keep and v}
    TIMING_FILE.write_text(
        '// Generated by tools/generate_audio.py: audio file id -> word timings per voice (m / f),\n'
        '// 4 numbers per word: start ms, end ms, end of the word in the text, syllables.\n'
        'window.TIMING = ' + json.dumps(data, separators=(',', ':')).replace('},"', '},\n"') + ';\n',
        encoding='utf-8')


def load_timing():
    if not TIMING_FILE.exists():
        return {}
    src = TIMING_FILE.read_text(encoding='utf-8')
    return json.loads(src[src.index('{'):src.rindex('}') + 1])


async def generate(sem, voice, folder, text, failures, timing):
    out = ROOT / 'audio' / folder / f'{key(text)}.mp3'
    have_audio = out.exists() and out.stat().st_size > 0
    slot = timing.setdefault(key(text), {})
    tag = folder[0]  # 'm' / 'f'
    if have_audio and tag in slot:
        return
    out.parent.mkdir(parents=True, exist_ok=True)
    async with sem:
        for attempt in range(4):
            try:
                # Word timings come with the speech. For a file that already exists the speech
                # is synthesized again only to read them (same voice, text and rate, so they match).
                audio, bounds = bytearray(), []
                async for chunk in edge_tts.Communicate(text, voice, rate=RATE, boundary='WordBoundary').stream():
                    if chunk['type'] == 'audio':
                        audio += chunk['data']
                    elif chunk['type'] == 'WordBoundary':
                        bounds.append(chunk)
                if not have_audio:
                    out.write_bytes(bytes(audio))
                slot[tag] = word_timing(text, bounds)
                print(f'{folder:6} {"timing " if have_audio else ""}{text}')
                PROGRESS['n'] += 1
                if PROGRESS['n'] % 200 == 0:  # save as it goes, so a stopped run loses little
                    save_timing(timing, PROGRESS['texts'])
                return
            except Exception as e:  # network hiccups: retry with backoff
                if attempt == 3:
                    failures.append((folder, text, repr(e)))
                await asyncio.sleep(2 * (attempt + 1))


async def main():
    texts = json.loads(subprocess.check_output(['node', str(ROOT / 'tools' / 'list-texts.js')], encoding='utf-8'))
    PROGRESS['texts'] = texts
    sem = asyncio.Semaphore(10)
    failures = []
    timing = load_timing()
    try:
        await asyncio.gather(*(generate(sem, v, f, t, failures, timing) for f, v in VOICES.items() for t in texts))
    finally:  # keep what was fetched even if the run is interrupted
        save_timing(timing, texts)

    manifest = {t: key(t) for t in sorted(texts)}
    # What "Download for offline" actually costs: every id, in both voices.
    files = [ROOT / 'audio' / f / f'{i}.mp3' for i in sorted(set(manifest.values())) for f in VOICES]
    total_bytes = sum(f.stat().st_size for f in files if f.exists())
    (ROOT / 'app' / 'audio-manifest.js').write_text(
        '// Generated by tools/generate_audio.py: Thai text -> audio file id.\n'
        'window.AUDIO = ' + json.dumps(manifest, ensure_ascii=False, indent=1) + ';\n'
        '// Every file the offline download fetches, both voices, in bytes.\n'
        f'window.AUDIO_BYTES = {total_bytes};\n',
        encoding='utf-8')
    print(f'{len(texts)} phrases x {len(VOICES)} voices; {len(failures)} failed')
    for f in failures:
        print('FAILED', *f)
    sys.exit(1 if failures else 0)


asyncio.run(main())
