"""Print every handwriting worksheet in printables/worksheets.js to PDF with headless Chrome or Edge.

Run after changing the worksheets:   python tools/build_worksheets.py [file ...]
Writes printables/<file>.pdf for each sheet (or only the sheets named on the command line),
reports layout problems the page finds (text running into the footer or off the edge),
and rewrites the table in printables/index.md, the site's Worksheets page.
Needs node (for reading worksheets.js) and Chrome or Edge.
"""
import html
import json
import pathlib
import re
import subprocess
import sys
import tempfile
import urllib.parse

ROOT = pathlib.Path(__file__).resolve().parent.parent
PRINTABLES = ROOT / 'printables'
BROWSERS = [
    r'C:\Program Files\Google\Chrome\Application\chrome.exe',
    r'C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe',
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    '/usr/bin/google-chrome',
]
TABLE_START = '<!-- worksheet table: generated by tools/build_worksheets.py -->'
TABLE_END = '<!-- end of worksheet table -->'


def load_sheets():
    script = ("global.window={};require(process.argv[1]);"
              "process.stdout.write(JSON.stringify(window.SHEETS))")
    out = subprocess.run(['node', '-e', script, str(PRINTABLES / 'worksheets.js')],
                         check=True, capture_output=True, encoding='utf-8').stdout
    return json.loads(out)


def write_index(sheets):
    """Fill the worksheet table on the Worksheets page from the sheet data."""
    rows = ['| Unit | Practise | Worksheet |', '|------|----------|-----------|']
    # Alphabet sheets first, then the units, then extras.
    for s in sorted(sheets, key=lambda s: (not s.get('kind'), not s['file'].startswith('unit-'))):
        if s.get('kind'):
            rows.append(f'| Alphabet · {s["title"]} | {s["summary"]} | [PDF]({s["file"]}.pdf) |')
            continue
        name = re.sub(r'^Unit (\d+) · ', r'\1 · ', s['title'])
        if not s['file'].startswith('unit-'):
            name = f'Extra · {name}'
        practise = []
        for i, x in enumerate(s['sentences']):
            # The practice rows keep the sentence's real spacing; the chunks don't.
            parts = [p[0] for p in s['practice'] if re.match(rf'Sentence {i + 1}\b', p[3])]
            thai = re.sub(r'(&nbsp;|\s)+', ' ', ''.join(parts)) if parts else ''.join(c[0] for c in x['chunks'])
            practise.append(f'<span class="thai">{thai}</span> {html.escape(x["en"], quote=False)}')
        practise = ' · '.join(practise)
        rows.append(f'| {name} | {practise} | [PDF]({s["file"]}.pdf) |')
    page = PRINTABLES / 'index.md'
    text = page.read_text(encoding='utf-8')
    start, end = text.index(TABLE_START) + len(TABLE_START), text.index(TABLE_END)
    page.write_text(text[:start] + '\n' + '\n'.join(rows) + '\n' + text[end:], encoding='utf-8')
    print('wrote printables/index.md')


def main():
    sys.stdout.reconfigure(encoding='utf-8')  # problem reports quote Thai text
    browser = next((b for b in BROWSERS if pathlib.Path(b).exists()), None)
    if not browser:
        sys.exit('Chrome or Edge not found')
    sheets = load_sheets()
    names = [s['file'] for s in sheets if len(sys.argv) == 1 or s['file'] in sys.argv[1:]]
    page = (PRINTABLES / 'worksheet.html').as_uri()
    failed = 0
    with tempfile.TemporaryDirectory() as profile:
        for name in names:
            out = PRINTABLES / f'{name}.pdf'
            url = f'{page}?s={urllib.parse.quote(name)}'
            common = [browser, '--headless=new', '--disable-gpu', '--virtual-time-budget=8000',
                      f'--user-data-dir={profile}']
            subprocess.run(common + ['--no-pdf-header-footer', f'--print-to-pdf={out}', url],
                           check=True, capture_output=True)
            dom = subprocess.run(common + ['--dump-dom', url], check=True, capture_output=True,
                                 encoding='utf-8').stdout
            problems = html.unescape(re.search(r'data-problems="([^"]*)"', dom).group(1)) \
                if 'data-problems="' in dom else 'page script did not finish'
            print('wrote', out.relative_to(ROOT), f'  PROBLEMS: {problems}' if problems else '')
            failed += bool(problems)
    write_index(sheets)
    if failed:
        sys.exit(f'{failed} worksheets have layout problems')


if __name__ == '__main__':
    main()
